import {writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {createConcordanceScenario,evaluateConcordance,searchConcordanceGrid,searchConcordanceLocal,searchConcordanceGlobal} from '../public/scripts/concordance-engine.mjs';
import {CONCORDANCE_RANDOM_ALGORITHM,randomizeConcordance} from '../public/scripts/concordance-scenarios.mjs';

// Selected illustrations, not a representative statistical sample. Running the
// script again recomputes every result; no optimum or multiplier is injected.
const seeds=[7,8,34];
const interpretations={
    7:'Meilleurs états différents, mais deux bornes encore ouvertes : aucun ordre des deux maxima n’est établi.',
    8:'Même meilleur état avec amplification ; borne fermée en rectifié, encore ouverte en signé.',
    34:'Un témoin signé dépasse la borne supérieure rectifiée, avec une production intermédiaire négative ; les deux maxima exacts restent non déterminés.',
};
const settings={
    grid:{divisions:10,maxEvaluations:200000},
    local:{initialStep:.1,minStep:1e-5,maxEvaluations:5000},
    global:{maxNodes:4000,tolerance:1e-5},
};
const point=state=>state?{
    objective:state.objective,controls:state.controls,
    algebraicArrivals:state.objectives.algebraicArrivals,
    absoluteArrivals:state.objectives.arrivals,
    negativeOutputNodes:state.nodes.filter(node=>node.output<0).map(node=>node.id),
    negativeRawNodes:state.nodes.filter(node=>node.rawOutput<0).map(node=>node.id),
}:null;
const summary=result=>Object.fromEntries(Object.entries({
    best:point(result.best),status:result.status,complete:result.complete,
    evaluations:result.evaluations,feasibleCount:result.feasibleCount,total:result.total,
    processedNodes:result.processedNodes,openNodes:result.openNodes,
    upperBound:result.upperBound,gap:result.gap,
}).filter(([,value])=>value!==undefined));

async function run() {
    const args=process.argv.slice(2);
    if(args.some(arg=>arg!=='--write')||args.length>1)throw new Error('Usage : node app/tools/etudier-concordances.mjs [--write]');
    const base=createConcordanceScenario();
    for(const id of Object.keys(base.environments))base.environments[id]=.5;
    const cases=[];
    for(const seed of seeds) {
        const model=randomizeConcordance(base,seed),modes={};
        for(const domain of ['rectified','signed']) {
            const options={domain,objective:'output'};
            const initial=evaluateConcordance(model,model.initialControls,options);
            const grid=searchConcordanceGrid(model,{...options,...settings.grid});
            const local=searchConcordanceLocal(model,{...options,...settings.local,initialControls:model.initialControls});
            const global=searchConcordanceGlobal(model,{...options,...settings.global,initialControls:model.initialControls});
            const candidates=[['initial',initial],['grid',grid.best],['local',local.best],['global',global.best]].filter(([,state])=>state?.feasible);
            candidates.sort((a,b)=>b[1].objective-a[1].objective);
            const [method,best]=candidates[0];
            modes[domain]={initial:point(initial),grid:summary(grid),local:summary(local),global:summary(global),
                bestObtained:{method,...point(best)},
                gapToBestObtained:global.upperBound===null?null:Math.max(0,global.upperBound-best.objective)};
        }
        cases.push({seed,interpretation:interpretations[seed],provenance:model.provenance,modes});
    }
    const data={schemaVersion:1,algorithm:CONCORDANCE_RANDOM_ALGORITHM,
        purpose:'Trois graines choisies pour illustrer des comportements, sans représentativité statistique.',
        model:{source:1,environments:base.environments,initialControls:base.initialControls},
        objective:'output',settings,cases,
        reproduction:'node app/tools/etudier-concordances.mjs --write',
        scope:'Les deux modes utilisent la même matrice pour chaque graine. Une borne ouverte ne devient pas un optimum prouvé.'};
    if(args.includes('--write')) {
        const target=new URL('../public/scripts/concordance-sample-results.mjs',import.meta.url);
        await writeFile(target,'// Generated by app/tools/etudier-concordances.mjs --write. Do not edit the calculated values.\nexport const CONCORDANCE_SAMPLE_RESULTS = '+JSON.stringify(data,null,2)+';\n','utf8');
        console.log(JSON.stringify({written:fileURLToPath(target),cases:cases.map(item=>({seed:item.seed,modes:Object.fromEntries(Object.entries(item.modes).map(([mode,value])=>[mode,{initial:value.initial.objective,best:value.bestObtained.objective,upper:value.global.upperBound,gap:value.gapToBestObtained,status:value.global.status}]))}))},null,2));
    } else console.log(JSON.stringify(data,null,2));
}
await run();
